// Declaracion de la funcion
sumar();
function sumar() {
    console.log(2 + 2);
}



// Expresion de la funcion
sumar2();
const sumar2 = function() {
    console.log(3 + 3);
}   


/* La diferencia entre una declaracion y una expresion de funcion es que la
 declaracion se puede llamar antes de su definicion, mientras que la expresion
  no. */